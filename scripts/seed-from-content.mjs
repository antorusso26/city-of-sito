// Genera supabase/seed.sql dai file in content/: area, città, città vicine, gruppi e pacchetto,
// categorie, partner segnaposto, esperienze, alberghi e case. Stessi slug del sito.
// Uso: node scripts/seed-from-content.mjs   poi carica il file dal pannello SQL di Supabase (o `supabase db reset`).
// Le schede con placeholder: true (o senza il campo) entrano con is_sample = true: prezzo null e partner [PARTNER] restano segnaposto.
// Le foto vanno caricate a parte nel bucket "listings" con lo stesso nome: node scripts/upload-photos.mjs
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const ROOT = path.join(process.cwd(), "content");
const read = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, f), "utf8"));
const q = (v) => (v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${(a ?? []).map(q).join(",")}]::text[]`;
const cents = (n) => (n === null || n === undefined ? "null" : Math.round(n * 100));
const json = (o) => `${q(JSON.stringify(o))}::jsonb`;
// Foto: in Storage (bucket "listings") con lo stesso nome del file in public/photos; credito e alt da credits.json.
const credits = JSON.parse(fs.readFileSync(path.join(process.cwd(), "public", "photos", "credits.json"), "utf8"));
const photoPath = (img) => img?.replace(/^\/photos\//, "") ?? null;
const photoRow = (city, slug, img) => {
  const file = photoPath(img);
  if (!file) return null;
  const c = credits[file.replace(/\.[a-z]+$/, "")] ?? {};
  return `insert into listing_photos (listing_id, path, alt, credit, position) select l.id, ${q(file)}, ${q(c.alt ?? "")}, ${q(c.by ? `${c.by} / Unsplash` : null)}, 0
  from listings l join cities c on c.id = l.city_id
  where c.slug = ${q(city)} and l.slug = ${q(slug)} and not exists (select 1 from listing_photos x where x.listing_id = l.id and x.path = ${q(file)});`;
};

function mdDir(dir) {
  const base = path.join(ROOT, dir);
  if (!fs.existsSync(base)) return [];
  return fs.readdirSync(base).flatMap((city) =>
    fs.readdirSync(path.join(base, city)).filter((f) => f.endsWith(".md")).map((f) => {
      const { data, content } = matter(fs.readFileSync(path.join(base, city, f), "utf8"));
      return { ...data, city, slug: f.replace(/\.md$/, ""), body: content.trim() };
    }));
}

const cities = read("cities.json");
const categories = read("categories.json");
const groups = read("groups.json");
const experiences = mdDir("experiences");
const stays = mdDir("stays");

const unit = { "per boat": "per_boat", "per person": "per_person", "per vehicle": "per_car", "per group": "per_group" };
const partnerKind = { "boat-tours": "boat", "cooking-classes": "food", food: "food", transfers: "driver", walks: "guide" };
const minutes = (d) => { const m = /(\d+(?:[.,½]\d*)?)\s*hour/.exec(d ?? ""); return m ? Math.round(parseFloat(m[1].replace("½", ".5")) * 60) : null; };

const out = ["-- Generated by scripts/seed-from-content.mjs — do not edit by hand.", "begin;"];

out.push(`insert into areas (slug, name, status) values ('amalfi-coast', 'Amalfi Coast', 'live') on conflict (slug) do update set status = excluded.status;`);

for (const c of cities) {
  out.push(`insert into cities (area_id, slug, name, status, helm_slot, accent, coords, tagline, intro, hero_path)
  select id, ${q(c.slug)}, ${q(c.name)}, ${q(c.status)}, ${c.helmSlot}, ${q(c.accent)}, ${q(c.coordinates)}, ${q(c.tagline)}, ${q(c.intro)}, ${q(c.hero)}
  from areas where slug = 'amalfi-coast'
  on conflict (slug) do update set status = excluded.status, helm_slot = excluded.helm_slot, accent = excluded.accent,
    coords = excluded.coords, tagline = excluded.tagline, intro = excluded.intro, hero_path = excluded.hero_path;`);
}
for (const c of cities) {
  (c.near ?? []).forEach((n, i) => out.push(`insert into city_links (city_id, near_id, rank)
  select a.id, b.id, ${i} from cities a, cities b where a.slug = ${q(c.slug)} and b.slug = ${q(n)} on conflict do nothing;`));
}

for (const g of groups) {
  out.push(`insert into city_groups (area_id, slug, name, summary, status) select id, ${q(g.slug)}, ${q(g.name)}, ${q(g.summary)}, 'published' from areas where slug = 'amalfi-coast'
  on conflict (slug) do update set name = excluded.name, summary = excluded.summary;`);
  g.cities.forEach((c, i) => out.push(`insert into city_group_members (group_id, city_id, position, optional)
  select g.id, c.id, ${i}, true from city_groups g, cities c where g.slug = ${q(g.slug)} and c.slug = ${q(c)} on conflict do nothing;`));
  out.push(`insert into packages (group_id, slug, name, summary, status) select id, ${q(g.slug)}, ${q(g.name)}, ${q(g.summary)}, 'published' from city_groups where slug = ${q(g.slug)}
  on conflict (slug) do nothing;`);
}

categories.forEach((c, i) => out.push(`insert into categories (slug, name, kind, position) values (${q(c.slug)}, ${q(c.name)}, 'experience', ${i}) on conflict (slug) do nothing;`));
out.push(`insert into categories (slug, name, kind, position) values ('hotels', 'Hotels', 'stay', 50), ('houses', 'Houses', 'stay', 51) on conflict (slug) do nothing;`);

// Un partner segnaposto per città e tipo, finché i partner veri non sono firmati.
const partnerName = (city, kind) => `[PARTNER] ${kind}, ${cities.find((c) => c.slug === city)?.name ?? city}`;
const partners = new Set([
  ...experiences.map((e) => `${e.city}|${partnerKind[e.category] ?? "other"}`),
  ...stays.map((s) => `${s.city}|${s.kind}`),
]);
for (const p of partners) {
  const [city, kind] = p.split("|");
  out.push(`insert into partners (kind, name, status, notes) select ${q(kind)}, ${q(partnerName(city, kind))}, 'lead', 'Placeholder from seed'
  where not exists (select 1 from partners where name = ${q(partnerName(city, kind))});`);
  out.push(`insert into partner_cities (partner_id, city_id) select p.id, c.id from partners p, cities c where p.name = ${q(partnerName(city, kind))} and c.slug = ${q(city)} on conflict do nothing;`);
}

for (const e of experiences) {
  const kind = partnerKind[e.category] ?? "other";
  const details = { format: e.format, duration: e.duration, groupSize: e.groupSize, departure: e.departure, priceUnit: e.priceUnit, faq: e.faq ?? [] };
  out.push(`insert into listings (kind, partner_id, city_id, category_id, slug, title, summary, body_md, why_we_picked, includes, excludes, duration_min, meeting_point, price_cents, price_unit, details, is_sample, status)
  select 'experience', p.id, c.id, k.id, ${q(e.slug)}, ${q(e.title)}, ${q(e.summary)}, ${q(e.body)}, ${q(e.whyWePickedIt)}, ${arr(e.included)}, ${arr(e.notIncluded)},
    ${minutes(e.duration) ?? "null"}, ${q(e.departure)}, ${cents(e.priceFrom)}, ${q(unit[e.priceUnit] ?? "per_group")}, ${json(details)}, ${e.placeholder !== false}, 'published'
  from partners p, cities c, categories k where p.name = ${q(partnerName(e.city, kind))} and c.slug = ${q(e.city)} and k.slug = ${q(e.category)}
  on conflict (city_id, slug) do update set title = excluded.title, summary = excluded.summary, body_md = excluded.body_md, why_we_picked = excluded.why_we_picked,
    includes = excluded.includes, excludes = excluded.excludes, duration_min = excluded.duration_min, meeting_point = excluded.meeting_point,
    price_cents = excluded.price_cents, price_unit = excluded.price_unit, details = excluded.details, is_sample = excluded.is_sample, category_id = excluded.category_id;`);
  const ep = photoRow(e.city, e.slug, e.image);
  if (ep) out.push(ep);
}

for (const s of stays) {
  out.push(`insert into listings (kind, partner_id, city_id, category_id, slug, title, summary, body_md, price_cents, price_unit, details, is_sample, status)
  select 'stay', p.id, c.id, k.id, ${q(s.slug)}, ${q(s.title)}, ${q(s.summary)}, ${q(s.body)}, ${cents(s.priceFrom)}, 'per_night', ${json({ sleeps: s.sleeps })}, ${s.placeholder !== false}, 'published'
  from partners p, cities c, categories k where p.name = ${q(partnerName(s.city, s.kind))} and c.slug = ${q(s.city)} and k.slug = ${q(s.kind === "hotel" ? "hotels" : "houses")}
  on conflict (city_id, slug) do update set title = excluded.title, summary = excluded.summary, body_md = excluded.body_md,
    price_cents = excluded.price_cents, details = excluded.details, is_sample = excluded.is_sample;`);
  const sp = photoRow(s.city, s.slug, s.image);
  if (sp) out.push(sp);
}

// Pacchetto: di default la prima esperienza di ogni città del gruppo.
for (const g of groups) {
  for (const c of g.cities) {
    const first = experiences.find((e) => e.city === c);
    if (first) out.push(`insert into package_items (package_id, listing_id, is_default) select p.id, l.id, true from packages p, listings l join cities c on c.id = l.city_id
  where p.slug = ${q(g.slug)} and c.slug = ${q(c)} and l.slug = ${q(first.slug)} on conflict do nothing;`);
  }
}

out.push("commit;");
fs.writeFileSync(path.join(process.cwd(), "supabase", "seed.sql"), out.join("\n") + "\n");
console.log(`supabase/seed.sql: ${cities.length} cities, ${experiences.length} experiences, ${stays.length} stays, ${partners.size} placeholder partners`);
